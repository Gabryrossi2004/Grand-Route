const NAMES_BY_CODE: Record<string, string[]> = {};
for (const [name, code] of Object.entries(CODE_BY_NAME)) (NAMES_BY_CODE[code] ??= []).push(name);

export const codeOf = (name: string): string | null => CODE_BY_NAME[name] ?? null;
// Il paese "principale" sul globo per un codice (il primo con quel codice)
export const namesOf = (code: string): string[] => NAMES_BY_CODE[code.toUpperCase()] ?? [];

// Bandierina emoji dal codice (es. "IT" → 🇮🇹)
export function flagOf(code: string): string {
  if (!/^[A-Z]{2}$/i.test(code)) return "";
  return String.fromCodePoint(...[...code.toUpperCase()].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));
}

// Nome italiano dal codice
export function nameItOfCode(code: string): string {
  try {
    return new Intl.DisplayNames(["it"], { type: "region" }).of(code.toUpperCase()) ?? code;
  } catch {
    return code;
  }
}

// Elenco dei paesi (codice + nome italiano) per i menu di scelta, in ordine alfabetico
export function countryOptions(): { code: string; name: string }[] {
  const seen = new Set<string>();
  const list: { code: string; name: string }[] = [];
  for (const code of Object.values(CODE_BY_NAME)) {
    if (seen.has(code) || code === "AQ" || code === "UM" || code === "CP") continue;
    seen.add(code);
    list.push({ code, name: nameItOfCode(code) });
  }
  return list.sort((a, b) => a.name.localeCompare(b.name, "it"));
}
